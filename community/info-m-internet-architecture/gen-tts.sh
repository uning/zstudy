#!/bin/bash
set -e
DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$DIR"

gen() {
  local n="$1"; local text="$2"
  if [ -s "tts/${n}.mp3" ]; then echo "skip ${n}"; return 0; fi
  edge-tts --voice zh-CN-XiaoyiNeural --rate="-8%" --text "$text" --write-media "tts/${n}.mp3" >/dev/null 2>&1
  echo "ok ${n}"
}

gen s01 "互联网结构与协议初识。你输入网址按回车，网页瞬间出现——中间发生了什么？数据怎么从你的手机飞到千里之外的服务器，再飞回来？这节课，拆开互联网的黑盒子，看看里面的结构与规则。"
gen s02 "你在北京输入 www.baidu.com，百度的服务器可能在上海、深圳、甚至美国——数据怎么知道该往哪走？又怎么保证不会迷路？靠的是两样东西：结构，互联网怎么组织；协议，通信的规则。结构回答往哪走，协议回答怎么走。"
gen s03 "今天的学习目标有四个：一、说出互联网的客户端-服务器架构；二、理解 IP 地址与域名的关系；三、说出 TCP/IP 四层模型的名称与作用；四、理解协议是通信双方约定的规则。"
gen s04 "互联网是什么？互联网是全球数十亿台设备通过统一的规则连接起来的巨型网络。它不是一个网络，而是无数个网络互相连接——家里的 Wi-Fi、学校的校园网、公司的内网，它们通过路由器互相连接，组成网络的网络。"
gen s05 "客户端-服务器架构。客户端是发起请求的一方，比如你的浏览器；服务器是响应请求的一方，比如存着网页数据的强大计算机。你刷网页等于客户端发请求、服务器找数据、服务器发回数据、客户端显示。"
gen s06 "互动：请求-响应角色扮演。你在浏览器输入网址，点击发送请求。浏览器把请求打包发给服务器，服务器找到网页数据，发回给你的浏览器，浏览器解析数据显示出网页。这就是请求-响应模式。"
gen s07 "IP 地址与域名。IP 地址是每台联网设备的门牌号，域名是 IP 地址的好记的名字。域名到 IP 地址的转换，由 DNS 域名系统完成——就像查电话簿。没有 DNS，上网就像要背下全世界的电话号码。"
gen s08 "互动：DNS 域名解析。输入域名，让 DNS 服务器帮你翻译成 IP 地址。点击开始解析，看 DNS 服务器返回什么结果。"
gen s09 "协议是什么？协议是通信双方事先约定好的规则。就像两个人打电话：先拨号建立连接，说喂你好打招呼，说正事传输数据，说再见结束连接。如果一方说中文、一方说英文——无法沟通。协议就是确保双方说同一种语言的规则。"
gen s10 "TCP/IP 四层模型。从上往下：第四层应用层，HTTP、DNS、SMTP，你直接用的协议；第三层传输层，TCP、UDP，确保数据完整到达；第二层网络层，IP，负责找路；第一层链路层，Wi-Fi、网线，真正跑路的物理通道。"
gen s11 "互动：数据包旅行记。点击出发，看一个数据包从你的手机到服务器的完整旅程。它会经过应用层、传输层、网络层、链路层，再经过路由器转发，最后到达服务器。"
gen s12 "三大易错点。一、以为互联网等于万维网——互联网是基础设施，万维网只是互联网上的一个应用。二、以为域名就是 IP——域名是给人看的名字，IP 是给机器看的地址。三、以为协议是某一层的事——每一层都有自己的协议。"
gen s13 "小测验基础关。第一题：客户端-服务器架构中，客户端是指？第二题：DNS 的作用是？"
gen s14 "小测验提高关。第一题：TCP/IP 四层模型从上到下依次是？第二题：关于协议，正确的说法是？"
gen s15 "今天学会了：互联网等于无数网络通过统一规则连接起来的网络的网络；客户端-服务器架构；IP 地址是门牌号，域名是好记的名字，DNS 负责翻译；协议是通信双方约定的规则；TCP/IP 四层模型：应用层、传输层、网络层、链路层。"
echo "ALL DONE"
