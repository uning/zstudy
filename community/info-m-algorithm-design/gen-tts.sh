#!/bin/bash
# G7 算法设计 TTS 生成脚本
set -e
DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$DIR"

gen() {
  local n="$1"; local text="$2"
  if [ -s "tts/${n}.mp3" ]; then echo "skip ${n}"; return 0; fi
  edge-tts --voice zh-CN-XiaoyiNeural --rate="-8%" --text "$text" --write-media "tts/${n}.mp3" >/dev/null 2>&1
  echo "ok ${n}"
}

gen s01 "算法设计与程序实现。导航 App 一秒算出最快路线，外卖平台毫秒匹配最近骑手——它们凭什么这么聪明？答案藏在一个词里：算法。这节课，从解决问题的方法出发，学会设计算法，并把它变成真正能跑的程序。"
gen s02 "从家到学校有一百种走法，导航 App 凭什么一秒钟告诉你这条最快？它会把一百条路都走一遍吗？当然不会。它用的是一套事先设计好的计算方法——输入起点终点，按规则一步步算，输出最优路线。这套计算方法，就叫算法。"
gen s03 "今天的学习目标有四个：一、说出算法的概念与五大特征；二、用流程图描述一个简单算法；三、理解算法效率的含义；四、看懂算法对应的简单程序代码。"
gen s04 "什么是算法？算法是解决一个问题所需要的、有限的、明确的、一步步可执行的方法。做菜有菜谱，洗衣有流程，这些都是算法——只不过由人执行。把算法写成程序，就能让计算机帮我们执行。"
gen s05 "算法的五大特征：一、有穷性，有限步内必须结束；二、确定性，每一步含义明确无歧义；三、可行性，每一步都能实际做到；四、输入，零个或多个输入；五、输出，至少一个结果。五大特征缺一个，都不能叫算法。"
gen s06 "互动：为泡茶设计算法。把五个步骤按正确顺序点击排列——烧开水、洗茶具、放入茶叶、注水冲泡、出汤品饮。想想：哪一步必须在最前面？哪一步必须在最后面？"
gen s07 "用流程图描述算法。文字描述算法容易歧义，工程师发明了流程图——用规定好的图形表达逻辑。圆角矩形表示开始或结束，矩形表示一个处理步骤，菱形表示判断，箭头表示执行方向。"
gen s08 "互动：排出判断是否及格的流程。点击节点，按算法执行顺序排一排。想想：先有什么——输入分数；再做什么——判断是否大于等于六十；最后得到什么——输出结果。"
gen s09 "算法效率：快一点，差很多。从一加到一百，笨办法要加九十九次，高斯办法只要三步。数字越大，差距越夸张——这就是算法效率。导航 App 不会真的走完所有路再比，它用图论算法只算最关键的几条。"
gen s10 "互动：找出八个数中的最大值。点击扫描下一个，看计算机怎么一步步找最大值——每扫一个，都要和当前最大比一次。注意观察：一共要比较多少次？"
gen s11 "三大易错点。一、以为算法就是程序——算法是思路，程序是代码实现。二、忽略有穷性——死循环不是算法。三、只看正确不看效率——数据量从八涨到八亿，效率差距会被无限放大。"
