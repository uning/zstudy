#!/bin/bash
set -e
DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$DIR"

gen() {
  local n="$1"; local text="$2"
  if [ -s "tts/${n}.mp3" ]; then echo "skip ${n}"; return 0; fi
  edge-tts --voice zh-CN-XiaoyiNeural --rate="-8%" --text "$text" --write-media "tts/${n}.mp3" >/dev/null 2>&1
  echo "ok ${n}"
}

gen s01 "云存储与在线协作。U盘丢了，所有资料一夜消失——这种事你遇到过吗？小组作业各改各的，最后版本对不上——这种混乱你经历过吗？这节课，认识互联网时代的文件管家：云存储与在线协作。"
gen s02 "小明的 U 盘丢了，里面有他做了三周的科创作品。他能找回来吗？如果文件只存在 U 盘里——找不回来了。如果文件存在云端——任何设备登录就能找回来。这就是云存储的核心价值：文件不依赖某一个设备。"
gen s03 "今天的学习目标有四个：一、说出云存储的概念与三大特征；二、理解在线协作同一份文档的核心思想；三、掌握版本管理与权限设置的基本操作；四、树立云端数据安全意识。"
gen s04 "什么是云存储？云存储是把文件保存在互联网上的服务器，也就是云端，而不是自己的电脑或 U 盘里。常见的云存储服务有百度网盘、阿里云盘、腾讯微云。共同点：文件在云端，账号在手，随时随地访问。"
gen s05 "云存储三大特征。一、随时随地访问：任何设备、任何地点，登录账号就能取文件。二、多设备同步：手机拍了照，电脑立刻能看到，自动同步。三、按需扩展：不够用了就扩容，不用买新硬盘。"
gen s06 "互动：本地存储 vs 云存储。本地存储像把钱藏在家里保险柜——安全但带不走；云存储像把钱存进银行——到处都能取，但要有密码。没有绝对好的存储方式，重要文件本地加云端双备份，才是真正的安全。"
gen s07 "在线协作的核心：同一份文档。传统协作：A 改完发给 B，B 改完发给 C，版本满天飞，最后对不上。在线协作：所有人打开同一个链接，实时看到彼此的修改，永远只有一份最新版本。"
gen s08 "互动：版本冲突怎么办？小明创建了文档，小红添加了图片，小刚修改了数据，小丽修正了格式。在线协作工具会自动保存每一次修改的历史版本——改错了可以回滚到任意版本。版本管理就像时间机器。"
gen s09 "权限与安全。云端文件不是谁都能看，可以设置分享权限：仅自己可见、指定人可见、任何人可查看、任何人可编辑。权限设置不当等于把日记本放在广场长椅上。重要文件一定要确认谁可以看、谁可以改。"
gen s10 "互动：该设什么权限？小组四人合作完成一份调研报告，该选哪种分享权限？仅自己可见？指定人可编辑？任何人可编辑？还是任何人可查看？"
gen s11 "三大易错点。一、以为上传到云就万事大吉——云端账号被盗、服务商倒闭都可能丢数据。二、以为分享链接等于安全——链接一旦泄露，任何人都能访问。三、以为云存储等于在线协作——先有云存储，才可能有在线协作。"
gen s12 "小测验基础关。第一题：云存储的核心价值是什么？第二题：在线协作相比传统方式的最大优势是？"
gen s13 "小测验提高关。第一题：关于云存储安全，正确的做法是？第二题：小组四人合作写报告，最合适的权限设置是？"
gen s14 "今天学会了：云存储等于文件保存在云端服务器，随时随地访问；三大特征：随时随地访问、多设备同步、按需扩展；在线协作核心：同一份文档，实时同步，版本可回滚；安全意识：权限设置、双备份、警惕链接泄露。"
