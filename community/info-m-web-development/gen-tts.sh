#!/bin/bash
set -e
DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$DIR"

gen() {
  local n="$1"; local text="$2"
  if [ -s "tts/${n}.mp3" ]; then echo "skip ${n}"; return 0; fi
  edge-tts --voice zh-CN-XiaoyiNeural --rate="-8%" --text "$text" --write-media "tts/${n}.mp3" >/dev/null 2>&1
  echo "ok ${n}"
}

gen s01 "网页与在线应用制作。你每天刷的网页、用的在线工具——它们是怎么长出来的？不是魔法，是三种技术的组合：HTML、CSS、JavaScript。这节课，学会用代码搭建一个属于自己的网页。"
gen s02 "同一个网页，为什么有的好看、有的难看？为什么有的能点、有的不能点？差别到底在哪？答案藏在网页的三层结构里：HTML 决定有什么，CSS 决定长什么样，JavaScript 决定能干什么。三层配合，网页才能既好看又好用。"
gen s03 "今天的学习目标有四个：一、说出网页的三层结构；二、认识常见 HTML 标签，能写简单网页；三、理解 CSS 控制样式、JS 控制交互；四、理解网页与在线应用的关系。"
gen s04 "网页是什么？网页是用 HTML 编写的、能在浏览器中显示的文档。网页不只"看"——现代网页还能"用"：在线文档、在线表格、在线地图、在线游戏。这些能用的网页，就叫在线应用。"
gen s05 "HTML：网页的骨架。HTML 用标签告诉浏览器这里有什么。标签是用尖括号括起来的关键词，比如 h1 表示一级标题，p 表示段落，img 表示图片，a 表示链接，button 表示按钮。HTML 像建筑图纸，告诉浏览器这里要放标题、这里要放段落。"
gen s06 "CSS：网页的皮肤。CSS 告诉浏览器长什么样——颜色、大小、位置、边框、阴影。没有 CSS，网页是毛坯房；有了 CSS，网页是精装修。HTML 说这里有个标题，CSS 说这个标题要橙色、三十二像素、居中。"
gen s07 "JavaScript：网页的大脑。JavaScript 让网页动起来——点击按钮、弹出提示、实时计算、加载数据。没有 JS，网页是静态海报；有了 JS，网页是互动应用。HTML 是骨架，CSS 是皮肤，JS 是大脑——三者缺一不可。"
gen s08 "互动：HTML 标签配对。点击左侧标签和右侧功能，把它们配成一对。h1 配一级标题，p 配段落文字，img 配插入图片，a 配超链接。"
gen s09 "互动：用 HTML 写一个段落。点击下方标签，把它们填入代码框，组成一个完整的 HTML 段落。段落要用 p 和斜杠 p 配对，标题要用 h1 和斜杠 h1 配对。"
gen s10 "在线应用：从网页到 App。简单网页等于 HTML 加 CSS 加 JS，只能看。在线应用等于 HTML 加 CSS 加 JS 加服务器数据加用户交互，能用。在线文档等于网页框架加界面样式加编辑功能加云端存储。"
gen s11 "互动：HTML、CSS、JS 各管什么？让标题变成橙色居中显示，是 CSS 的工作。在网页中插入一张图片，是 HTML 的工作。点击按钮后弹出提示框，是 JavaScript 的工作。"
gen s12 "三大易错点。一、以为 HTML 等于编程——HTML 是标记语言，不是编程语言，真正的编程是 JavaScript。二、以为 CSS 只是美化——CSS 还管布局，没有 CSS 网页会乱成一团。三、以为网页等于网站——一个网站由很多网页组成，还可能包含数据库和服务器程序。"
gen s13 "小测验基础关。第一题：HTML 的作用是？第二题：CSS 的作用是？"
gen s14 "小测验提高关。第一题：关于网页与在线应用，正确的说法是？第二题：一个按钮点击后弹出提示，这个功能由哪一层实现？"
gen s15 "今天学会了：网页是用 HTML 编写的、能在浏览器中显示的文档；三层结构：HTML 管结构、CSS 管样式、JS 管交互；在线应用等于网页加用户交互加服务器数据；常见 HTML 标签：h1 标题、p 段落、img 图片、a 链接、button 按钮。"
echo "ALL DONE"
